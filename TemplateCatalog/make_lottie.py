#!/usr/bin/env python3
"""Writes LottieBuiltIn.swift: the animated stickers and titles inside Sunroom (a few KB each)."""
import os
from lottie_kit import *

BUILT_IN = [
    # id, title, SF Symbol, animation
    ("pop-title", "Pop Title", "textformat", pop_title("Pop Title", "WOW!", (1, 0.88, 0.15))),
    ("sparkles", "Sparkles", "sparkles", sparkle_burst("Sparkles")),
    ("heart-pop", "Heart Pop", "heart.fill", heart_pop("Heart Pop")),
    ("underline", "Underline", "scribble", underline("Underline")),
    ("circle-it", "Circle It", "circle.dashed", circle_highlight("Circle It")),
    ("arrow", "Look Here", "arrow.down", arrow("Look Here")),
    ("confetti", "Confetti", "party.popper", confetti("Confetti")),
    ("follow", "Follow Button", "person.badge.plus", badge("Follow Button", "FOLLOW", (1, 0.23, 0.36))),
    ("lower-third", "Name Tag", "rectangle.bottomthird.inset.filled", lower_third("Name Tag", "Your Name", "what you do")),
    ("stars", "5 Stars", "star.fill", stars_rating("5 Stars")),
]

here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, "..", "Sources", "iUtility", "Video", "LottieBuiltIn.swift")
lines = ["// Generated by TemplateCatalog/make_lottie.py. Don't edit by hand.",
         "// Sunroom's own animations, drawn from shapes and text.", "",
         "enum LottieBuiltIn {",
         "    static let all: [(id: String, title: String, symbol: String, json: String)] = ["]
total = 0
for id_, title, symbol, a in BUILT_IN:
    js = dumps(a)
    total += len(js)
    lines.append(f'        ("{id_}", "{title}", "{symbol}", #"{js}"#),')
lines += ["    ]", "}", ""]
open(dst, "w").write("\n".join(lines))
print(f"{len(BUILT_IN)} animations, {total // 1024} KB")
